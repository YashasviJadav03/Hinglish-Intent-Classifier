def download_or_generate_dataset() -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Returns the expanded canonical base dataset (840 samples) and the OOD benchmark dataset (120 samples).
    """
    logger.info("Acquiring expanded canonical base Hinglish intent utterances (840 base items)...")
    curated_df = generate_curated_voice_agent_hinglish_data()

    logger.info("Acquiring independent Out-of-Distribution (OOD) benchmark dataset (120 samples)...")
    ood_df = generate_ood_benchmark_dataset()

    return curated_df, ood_df


